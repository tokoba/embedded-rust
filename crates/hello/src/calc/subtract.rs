/// 減算関数
///
/// 2つのi32値を受け取り、最初の値から2番目の値を引いた結果を返します
///
/// # 引数
///
/// * `a` - 引かれる数値
/// * `b` - 引く数値
///
/// # 戻り値
///
/// aからbを引いた結果
///
/// # 例
///
/// ```
/// use hello::calc::subtract;
///
/// let result = subtract(10, 3);
/// assert_eq!(result, 7);
/// ```
pub fn subtract(a: i32, b: i32) -> i32 {
  a - b
}
